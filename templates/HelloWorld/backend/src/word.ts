/**
 * Word Examples
 *
 * Demonstrates .docx creation and reading using ketrics.Word (requires
 * @ketrics/sdk-backend >= 0.21.0). Like Excel and Pdf it runs inside the
 * sandbox, so the builder methods are ordinary local calls.
 */

import { attachmentDisposition, demoVolumeCode } from "./helpers";
import { requirePermission } from "./permissions";

const DOCX_CONTENT_TYPE = "application/vnd.openxmlformats-officedocument.wordprocessingml.document";

/**
 * Create a simple Word document and save it to a volume.
 */
const createSimpleWord = async () => {
  requirePermission("export");

  const doc = ketrics.Word.create({
    pageSize: "A4",
    title: "Sample Document",
    author: ketrics.tenant.name,
  });

  doc
    .setFooter("Page {page} of {pages}")
    .addHeading("Hello from Ketrics!", 1)
    .addParagraph([
      `Generated by ${ketrics.application.name} for ${ketrics.tenant.name}. `,
      { text: "This text is bold and coloured.", bold: true, color: "2B3A99" },
    ])
    .addList(["Headings", "Styled paragraphs", { text: "Lists and tables", italic: true }])
    .addTable(
      [
        ["Item", "Hours", "Amount"],
        ["Design", 4, 400],
        ["Build", 12, 850],
      ],
      { headerRow: true, columnWidths: [3, 1, 1] },
    )
    .addParagraph(`Date: ${new Date().toISOString()}`, { spacingBefore: 12 });

  // Save to volume
  const buffer = await doc.toBuffer();
  const volume = await ketrics.Volume.connect(demoVolumeCode());
  const result = await volume.put("documents/sample.docx", buffer, {
    contentType: DOCX_CONTENT_TYPE,
  });

  // responseContentDisposition is required — a presigned S3 URL without it is
  // blocked by the iframe CSP and fails silently.
  const downloadUrl = await volume.generateDownloadUrl("documents/sample.docx", {
    expiresIn: 3600,
    responseContentDisposition: attachmentDisposition("sample.docx"),
  });

  return {
    file: { key: result.key, size: result.size },
    downloadUrl: downloadUrl.url,
  };
};

/**
 * Read a .docx file from the volume and return its text and blocks.
 * Defaults to the document createSimpleWord saves.
 */
const readWordDocument = async (payload?: { key?: string }) => {
  requirePermission("read");

  const key = payload?.key || "documents/sample.docx";
  const volume = await ketrics.Volume.connect(demoVolumeCode());

  if (!(await volume.exists(key))) {
    return { error: `File not found: ${key}. Run createSimpleWord first.` };
  }

  const file = await volume.get(key);
  try {
    const { text, blocks, properties } = await ketrics.Word.read(file.content);
    return { key, text, blocks, properties };
  } catch (error) {
    if (error instanceof ketrics.Word.ParseError) {
      return { error: "The file is not a readable Word document." };
    }
    throw error;
  }
};

export { createSimpleWord, readWordDocument };
